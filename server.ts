import 'dotenv/config';
import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import { GoogleGenAI, Type } from '@google/genai';
import { normalizeTheSportsDbEvents } from './src/engine/fixtureSources';
import { SportId } from './src/types/sports';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PORT = 3000;

function getGenAIClient(): GoogleGenAI {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY' || apiKey.trim() === '') {
    throw new Error(
      'GEMINI_API_KEY is not configured yet. Configure your key in Settings > Secrets to run Gemini-assisted research.'
    );
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

async function startServer() {
  const app = express();
  app.disable('x-powered-by');
  app.use(express.json({ limit: '256kb' }));

  // Basic abuse guard for public demo deployments. This is not a substitute for authentication.
  const requestWindows = new Map<string, { start: number; count: number }>();
  app.use(['/api/ai', '/api/sports'], (req, res, next) => {
    const now = Date.now();
    const key = req.ip || req.socket.remoteAddress || 'unknown';
    const current = requestWindows.get(key);
    if (!current || now - current.start >= 60_000) {
      requestWindows.set(key, { start: now, count: 1 });
      next();
      return;
    }
    current.count += 1;
    if (current.count > 12) {
      res.status(429).json({ error: 'Too many API requests. Please wait one minute and try again.' });
      return;
    }
    next();
  });

  app.get('/api/health', (_req, res) => {
    const hasKey = Boolean(
      process.env.GEMINI_API_KEY &&
        process.env.GEMINI_API_KEY !== 'MY_GEMINI_API_KEY' &&
        process.env.GEMINI_API_KEY.trim() !== ''
    );
    res.json({ ok: true, geminiConfigured: hasKey });
  });

  // Source-backed schedule discovery. It returns provider records only, never invented odds or rule scores.
  const scheduleCache = new Map<string, { expiresAt: number; events: unknown[] }>();
  const providerCallsByUtcDay = new Map<string, number>();
  app.post('/api/sports/discover-fixtures', async (req, res) => {
    try {
      const { date, sport } = req.body ?? {};
      const allowedSports = new Set(Object.values(SportId));
      if (typeof date !== 'string' || !/^\\d{4}-\\d{2}-\\d{2}$/.test(date) ||
          Number.isNaN(Date.parse(`${date}T00:00:00Z`)) ||
          typeof sport !== 'string' || !allowedSports.has(sport as SportId)) {
        res.status(400).json({ error: 'A valid YYYY-MM-DD date and supported sport are required.' });
        return;
      }

      const now = Date.now();
      let events = scheduleCache.get(date);
      if (!events || events.expiresAt <= now) {
        const utcDay = new Date(now).toISOString().slice(0, 10);
        const callsToday = providerCallsByUtcDay.get(utcDay) ?? 0;
        if (callsToday >= 3) {
          res.status(429).json({
            error: 'The free schedule source has a three-uncached-request daily limit. Reuse a cached date or retry after the UTC day changes.',
          });
          return;
        }
        providerCallsByUtcDay.set(utcDay, callsToday + 1);

        const response = await fetch(
          `https://www.thesportsdb.com/api/v1/json/123/eventsday.php?d=${encodeURIComponent(date)}`,
          { headers: { accept: 'application/json' }, signal: AbortSignal.timeout(8000) }
        );
        if (!response.ok) {
          throw new Error(`TheSportsDB returned HTTP ${response.status}.`);
        }
        const payload = await response.json() as { events?: unknown[] | null };
        if (payload.events === null) {
          events = { expiresAt: now + 12 * 60 * 60 * 1000, events: [] };
        } else if (Array.isArray(payload.events)) {
          events = { expiresAt: now + 12 * 60 * 60 * 1000, events: payload.events };
        } else {
          throw new Error('TheSportsDB returned an unexpected schedule response; no fixtures were accepted.');
        }
        scheduleCache.set(date, events);
      }

      const candidates = normalizeTheSportsDbEvents(events.events, sport as SportId, date);
      res.json({
        provider: 'TheSportsDB',
        providerNotice: 'Provider-listed schedule records only. Rule scores, odds, and prediction evidence are not generated by this endpoint.',
        date,
        sport,
        fetchedAt: new Date().toISOString(),
        sourceUrl: 'https://www.thesportsdb.com/',
        candidates,
      });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unable to retrieve source-backed schedule records.';
      res.status(502).json({ error: message });
    }
  });

  app.post('/api/ai/calibrate-notes', async (req, res) => {
    try {
      const { modelEngine, accuracy, brier, topFeatures, sampleTeams } = req.body ?? {};
      if (typeof modelEngine !== 'string' || modelEngine.length > 120 ||
          typeof accuracy !== 'number' || !Number.isFinite(accuracy) || accuracy < 0 || accuracy > 1 ||
          typeof brier !== 'number' || !Number.isFinite(brier) || brier < 0 || brier > 1) {
        res.status(400).json({ error: 'Valid model name, accuracy (0–1), and Brier score (0–1) are required.' });
        return;
      }
      const ai = getGenAIClient();
      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: `You are a quantitative sports modeling analyst. Summarize calibration findings in 2 concise sentences (under 45 words) for model "${modelEngine}" achieving ${(Number(accuracy || 0) * 100).toFixed(1)}% validation accuracy and ${Number(brier || 0.2).toFixed(4)} Brier score. Top learned rule weights: ${JSON.stringify(topFeatures)}. Sample calibrated teams: ${JSON.stringify(sampleTeams)}.`,
      });
      res.json({
        meta_improvement_notes: (response.text ?? '').trim(),
      });
    } catch (error) {
      const message =
        error instanceof Error ? error.message : 'Failed to synthesize meta-improvement notes.';
      res.status(500).json({ error: message });
    }
  });

  // Grounded post-match settlement audit for yesterday's (T-1) locked predictions
  app.post('/api/ai/audit-results', async (req, res) => {
    try {
      const { date, sport, picks } = req.body ?? {};
      if (typeof date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
          !Array.isArray(picks) || picks.length === 0 || picks.length > 15 ||
          picks.some((p: unknown) => !p || typeof p !== 'object' ||
            typeof (p as Record<string, unknown>).id !== 'string' || String((p as Record<string, unknown>).id).length > 128 ||
            typeof (p as Record<string, unknown>).selection !== 'string' || String((p as Record<string, unknown>).selection).length > 120 ||
            typeof (p as Record<string, unknown>).opponent !== 'string' || String((p as Record<string, unknown>).opponent).length > 120 ||
            typeof (p as Record<string, unknown>).market !== 'string' || String((p as Record<string, unknown>).market).length > 80)) {
        res.status(400).json({ error: 'A valid date and 1–15 well-formed picks are required.' });
        return;
      }

      const ai = getGenAIClient();
      const compactList = picks
        .map(
          (p: Record<string, unknown>) =>
            `- ID: ${String(p.id)} | ${String(p.selection)} vs ${String(p.opponent)} (${String(p.competition)}, Market: ${String(p.market)})`
        )
        .join('\n');

      const searchResp = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: `Search for official final match results and scores around ${date} for these ${sport || 'multi-sport'} events:\n${compactList}\nSummarize the actual final score or tournament standing for each listed matchup.`,
        config: {
          tools: [{ googleSearch: {} }],
        },
      });

      const groundingRaw = searchResp.candidates?.[0]?.groundingMetadata?.groundingChunks ?? [];
      const sources = groundingRaw
        .map((c) => (c.web ? { uri: c.web.uri ?? '', title: c.web.title ?? '' } : null))
        .filter((s): s is { uri: string; title: string } => Boolean(s && s.uri));

      const structResp = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: `Grade each locked prediction below using the verified final results briefing. If a match has not finished or no verified final result is found, set status to "pending" and actualOutcome to -1. Otherwise set status to "settled" and actualOutcome to 1 (selection won the market) or 0 (selection lost).\n\nLocked Picks:\n${compactList}\n\nVerified Results Briefing:\n${searchResp.text ?? ''}`,
        config: {
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.ARRAY,
            items: {
              type: Type.OBJECT,
              properties: {
                id: { type: Type.STRING },
                status: { type: Type.STRING },
                actualOutcome: { type: Type.INTEGER },
                scoreSummary: { type: Type.STRING },
              },
              required: ['id', 'status', 'actualOutcome', 'scoreSummary'],
            },
          },
        },
      });

      const settlements = JSON.parse((structResp.text ?? '[]').trim());
      res.json({
        settlements,
        briefing: searchResp.text ?? '',
        sources,
      });
    } catch (error) {
      const message =
        error instanceof Error ? error.message : 'Failed to audit final match results.';
      res.status(500).json({ error: message });
    }
  });

  if (process.env.NODE_ENV === 'production') {
    const distPath = path.join(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  } else {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`OctaNet server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
